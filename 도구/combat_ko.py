def _read(tok):
    if tok in TOKEN:
        return TOKEN[tok]
    # 숫자가 붙은 형태(狼1, 難度2)는 떼어 내고 읽는다
    head = tok.rstrip('0123456789')
    tail = tok[len(head):]
    if head and head != tok and head in TOKEN:
        return TOKEN[head] + tail
    out = [HANJA.get(ch, ch) for ch in head]
    return (''.join(out) or head) + tail


def combat_ko(desc):
    """'唐門大亂鬥 伙房 嵩山弟子' -> '당문 대난투 · 부엌 · 숭산파 제자'"""
    if not desc:
        return desc
    parts = [_read(t) for t in desc.split()]
    return ' · '.join(p for p in parts if p)
